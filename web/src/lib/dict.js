export function translate(key, lang, vars) {
  const entry = dict[key];
  let value = entry ? entry[lang === 'fa' ? 0 : 1] : key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      value = value.replaceAll(`{${k}}`, String(v));
    }
  }
  return value;
}
